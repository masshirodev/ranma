#!/bin/sh
# Write the Homebrew formula for a release to stdout: Formula/ranma.rb in
# masshirodev/homebrew-tap. release.yml's homebrew job runs it after each
# release and pushes the result; nothing else edits the tap.
#
# Usage: packaging/brew/formula.sh VERSION DIR [BASE_URL]
#
# DIR holds the release's ranma-VERSION-TARGET.tar.gz.sha256 files. BASE_URL
# is where the tarballs are downloaded from, by default the GitHub release;
# packaging/test/run.sh brew points it at file:///dist.
set -eu

version="${1:?usage: formula.sh VERSION DIR [BASE_URL]}"
dir="${2:?usage: formula.sh VERSION DIR [BASE_URL]}"
base="${3:-https://github.com/masshirodev/ranma/releases/download/v$version}"

sum() {
  f="$dir/ranma-$version-$1.tar.gz.sha256"
  [ -f "$f" ] || { echo "no $f" >&2; exit 1; }
  cut -d' ' -f1 "$f"
}
x86="$(sum x86_64-unknown-linux-gnu)"
arm="$(sum aarch64-unknown-linux-gnu)"

cat <<EOF
# Generated by packaging/brew/formula.sh in masshirodev/ranma on each release.
# Change it there: this file is overwritten.
class Ranma < Formula
  desc "Tiling window manager for the terminal, where every window is a PTY"
  homepage "https://github.com/masshirodev/ranma"
  license any_of: ["MIT", "Apache-2.0"]

  # Linux only until ranma runs on macOS (doc/ROADMAP.md, milestone 15).
  depends_on :linux

  on_linux do
    on_intel do
      url "$base/ranma-$version-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$x86"
    end
    on_arm do
      url "$base/ranma-$version-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$arm"
    end
  end

  def install
    bin.install "ranma"
    man1.install Dir["man/man1/*"]
    man5.install Dir["man/man5/*"]
    man7.install Dir["man/man7/*"]
  end

  def caveats
    <<~EOS
      After an upgrade, check your config against the new build, then move
      running servers onto it (shells and scrollback stay):
        ranma --check-config && ranma upgrade --all
      If the check fails, a terminal that starts ranma falls back to a plain
      shell until the config is fixed.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ranma --version")
    system bin/"ranma", "--check-config"
  end
end
EOF
