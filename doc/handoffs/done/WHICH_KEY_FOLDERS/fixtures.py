# Writes the which-key text fixtures src/whichkey.rs tests against, from wk.py
# (the handoff's port of the layout) and gen.py (the folders handoff's config).
# Run from this directory: python3 fixtures.py. Rerun when the default binds
# change, after updating the D_* rows in wk.py to what they now show.
from wk import layout, text, DEFAULTS, STRIP, F_PANE, F_LAYOUTS
from gen import TOP, GIT, BR, EMPTY_TOP, EMPTY

CR = ['ctrl+b']


def panels(spec):
    out = []
    for name, groups, sw, sh, keys, border in spec:
        p = layout(groups, sw, sh, CR + keys, back=bool(keys))
        out.append('## ' + name + '\n' + '\n'.join(text(p, border)) + '\n')
    return out


def write(path, header, spec, sep):
    with open(path, 'w') as f:
        f.write(header + sep + sep.join(panels(spec)))


write('../WHICH_KEY_MOCK.txt',
      "# The which-key hint's panels for the default binds, cell for cell.\n"
      "# Drawn first by the design handoff (Which-key hint grid alignment.zip);\n"
      "# redrawn 2026-10-09 by its own layout, WHICH_KEY_FOLDERS/wk.py, when the\n"
      "# defaults gained settings, the tmux extras and two folders.\n"
      "# Regenerate with WHICH_KEY_FOLDERS/fixtures.py; src/whichkey.rs tests these.\n",
      [('80x24 rounded', DEFAULTS, 80, 24, [], True),
       ('80x24 none', DEFAULTS, 80, 24, [], False),
       ('120x35 rounded', DEFAULTS, 120, 35, [], True),
       ('200x50 rounded', DEFAULTS, 200, 50, [], True),
       ('40x15 flowed', DEFAULTS, 40, 15, [], True),
       ('80x24 pane rounded', F_PANE, 80, 24, ['x'], True),
       ('80x24 layouts rounded', F_LAYOUTS, 80, 24, ['y'], True)],
      '')

