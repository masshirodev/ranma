       ('80x24 git none', GIT, 80, 24, ['g'], False),
       ('120x35 top rounded', TOP, 120, 35, [], True),
       ('120x35 git rounded', GIT, 120, 35, ['g'], True),
       ('200x50 top rounded', TOP, 200, 50, [], True),
       ('40x15 git flowed', GIT, 40, 15, ['g'], True),
       ('40x15 top flowed', TOP, 40, 15, [], True),
       ('120x35 empty folder in top rounded', EMPTY_TOP, 120, 35, [], True),
